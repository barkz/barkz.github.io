#!/usr/bin/env python3
"""Build the site's shared copy and the blog. No dependencies.

    python3 tools/build-site.py           # update pages, write blog posts
    python3 tools/build-site.py --check   # change nothing; exit 1 if out of date

The Build site GitHub Action (.github/workflows/build-site.yml) runs this
after every push to main and commits the result, so running it locally is
only needed to preview.

Pages stay plain HTML. Shared pieces live between markers and are
rewritten in place on every run:

    <!-- build:nav --> ... <!-- /build -->            partials/nav.html
    <!-- build:mail askus --> ... <!-- /build -->     partials/mail.html, address from site.json
    <!-- build:text launch.short -->Dec 15, 2026<!-- /build -->

Regions: head, nav, orb, footer, scripts, posts (blog.html), mail <key>,
text <key>. Everything outside a region is yours to edit and is never
touched. Shared values (emails, launch date, year, the ?v= asset version,
page titles and descriptions) live in site.json.

Blog posts are posts/topic-YYYY-MM-DD.md. Each becomes its own page,
blog/topic.html, from partials/post.html, and blog.html lists them newest
first. The first "# Heading" is the title and the first paragraph the
excerpt. Generated posts carry a header comment; a generated post whose
markdown is gone is deleted.
"""

import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PARTIALS = os.path.join(ROOT, "partials")
POSTS = os.path.join(ROOT, "posts")
BLOG = os.path.join(ROOT, "blog")
GENERATED = "Generated by tools/build-site.py"

POST_NAME = re.compile(r"^(?P<topic>[a-z0-9][a-z0-9._-]*)-(?P<date>\d{4}-\d{2}-\d{2})\.md$")
REGION = re.compile(r"<!-- build:(?P<name>[\w-]+)(?: (?P<arg>[\w.-]+))? -->(?P<body>.*?)<!-- /build -->", re.S)
PLACEHOLDER = re.compile(r"\{\{\s*(?:(?P<op>html|current)\s+)?(?P<key>[\w.-]+)\s*\}\}")
MONTHS = ["JANUARY", "FEBRUARY", "MARCH", "APRIL", "MAY", "JUNE", "JULY",
          "AUGUST", "SEPTEMBER", "OCTOBER", "NOVEMBER", "DECEMBER"]
EXCERPT_CHARS = 190


class BuildError(Exception):
    pass


# ---------- templates ------------------------------------------------------
# {{key}} inserts an escaped value (dotted keys reach into site.json),
# {{html key}} inserts trusted HTML as is, and {{current blog}} becomes
# aria-current="page" on the page whose nav key is "blog".

def lookup(ctx, key):
    value = ctx
    for part in key.split("."):
        if not isinstance(value, dict) or part not in value:
            raise BuildError("unknown value {{%s}}" % key)
        value = value[part]
    return value


def fill(text, ctx):
    def sub(m):
        op, key = m.group("op"), m.group("key")
        if op == "current":
            return ' aria-current="page"' if ctx.get("nav") == key else ""
        value = lookup(ctx, key)
        return str(value) if op == "html" else html.escape(str(value))
    return PLACEHOLDER.sub(sub, text)


def partial(name, ctx):
    path = os.path.join(PARTIALS, name + ".html")
    with open(path, encoding="utf-8") as fh:
        return fill(fh.read().rstrip("\n"), ctx)


# ---------- regions --------------------------------------------------------

def region_html(name, arg, ctx):
    if name in ("head", "nav", "orb", "footer"):
        return partial(name, ctx)
    if name == "scripts":
        return "\n".join('<script src="%s%s?v=%s"></script>' % (ctx["root"], src, ctx["version"])
                         for src in ["site.js"] + ctx["page"].get("scripts", []))
    if name == "mail":
        return partial("mail", dict(ctx, addr=lookup(ctx, "email." + (arg or ""))))
    if name == "text":
        return html.escape(str(lookup(ctx, arg or "")))
    if name == "posts":
        rows = [partial("post-row", dict(ctx, post=p)) for p in ctx["posts"]]
        return "\n".join(rows) or '<p class="empty">Nothing written yet. Soon.</p>'
    raise BuildError("unknown region build:%s" % name)


def build_regions(text, ctx, where):
    def sub(m):
        name, arg = m.group("name"), m.group("arg")
        try:
            body = region_html(name, arg, ctx)
        except BuildError as e:
            raise BuildError("%s: build:%s: %s" % (where, name, e))
        if "\n" not in body and name in ("text", "mail"):
            return "<!-- build:%s%s -->%s<!-- /build -->" % (name, " " + arg if arg else "", body)
        # block regions keep the marker's indentation
        line_start = text.rfind("\n", 0, m.start()) + 1
        indent = text[line_start:m.start()]
        if indent.strip():
            indent = ""
        inner = "\n".join(indent + line if line else line for line in body.split("\n"))
        return "<!-- build:%s%s -->\n%s\n%s<!-- /build -->" % (name, " " + arg if arg else "", inner, indent)
    return REGION.sub(sub, text)


# ---------- markdown -------------------------------------------------------
# Headings, **bold**, *italic*, `code`, fenced code, links, images, lists,
# blockquotes and rules. Raw HTML is escaped rather than passed through.
# "# Title" is the post title; "#" and "##" in the body are sections (h2),
# "###" is h3, "####" and deeper h4. Relative links and images are written
# from the site root (images/x.png) and fixed up for blog/.

def heading_id(text, used):
    base = re.sub(r"[^a-z0-9]+", "-", re.sub(r"<[^>]+>|&\w+;", "", text).lower()).strip("-") or "section"
    slug, n = base, 2
    while slug in used:
        slug, n = "%s-%d" % (base, n), n + 1
    used.add(slug)
    return slug


def render_markdown(src):
    stash, used = [], set()

    def keep(fragment):
        stash.append(fragment)
        return "@@WB%d@@" % (len(stash) - 1)

    def url(u):
        u = u.strip()
        if re.match(r"javascript:", u, re.I):
            return "#"
        if not re.match(r"([a-z][a-z0-9+.-]*:|/|#)", u, re.I):
            u = "../" + u
        return u.replace('"', "%22")

    def inline(t):
        t = re.sub(r'!\[([^\]]*)\]\(([^)\s]+)(?:\s+"[^"]*")?\)',
                   lambda m: '<img src="%s" alt="%s" loading="lazy">' % (url(m.group(2)), m.group(1)), t)
        t = re.sub(r'\[([^\]]+)\]\(([^)\s]+)(?:\s+"[^"]*")?\)',
                   lambda m: '<a href="%s">%s</a>' % (url(m.group(2)), m.group(1)), t)
        t = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", t)
        t = re.sub(r"(^|[^*\w])\*([^*\n]+)\*", r"\1<em>\2</em>", t)
        return re.sub(r"(^|[^_\w])_([^_\n]+)_", r"\1<em>\2</em>", t)

    text = re.sub(r"\r\n?", "\n", src).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"^```[^\n]*\n(.*?)^```[ \t]*$",
                  lambda m: keep("<pre><code>%s</code></pre>" % m.group(1).rstrip("\n")), text, flags=re.S | re.M)
    text = re.sub(r"`([^`\n]+)`", lambda m: keep("<code>%s</code>" % m.group(1)), text)

    out = []
    for block in re.split(r"\n{2,}", text):
        block = block.strip("\n")
        if not block:
            continue
        if re.fullmatch(r"@@WB\d+@@", block):
            out.append(block)
            continue
        m = re.fullmatch(r"(#{1,6})\s+(.+)", block, re.S)
        if m:
            level = min(max(len(m.group(1)), 2), 4)
            inner = inline(m.group(2).replace("\n", " "))
            out.append('<h%d id="%s">%s</h%d>' % (level, heading_id(inner, used), inner, level))
        elif re.fullmatch(r"-{3,}|\*{3,}|_{3,}", block):
            out.append("<hr>")
        elif block.startswith("&gt;"):
            out.append("<blockquote>%s</blockquote>" % inline(re.sub(r"^&gt;[ \t]?", "", block, flags=re.M).replace("\n", " ")))
        elif re.match(r"[-*+][ \t]+", block):
            items = re.split(r"\n(?=[-*+][ \t]+)", block)
            out.append("<ul>%s</ul>" % "".join("<li>%s</li>" % inline(re.sub(r"\n\s*", " ", re.sub(r"^[-*+][ \t]+", "", li))) for li in items))
        elif re.match(r"\d+[.)][ \t]+", block):
            items = re.split(r"\n(?=\d+[.)][ \t]+)", block)
            out.append("<ol>%s</ol>" % "".join("<li>%s</li>" % inline(re.sub(r"\n\s*", " ", re.sub(r"^\d+[.)][ \t]+", "", li))) for li in items))
        else:
            out.append("<p>%s</p>" % inline(block.replace("\n", " ")))

    return re.sub(r"@@WB(\d+)@@", lambda m: stash[int(m.group(1))], "\n".join(out))


# ---------- posts ----------------------------------------------------------

def strip_markdown(text):
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"(?<![\w*])([*_]{1,3})(?=\S)(.+?)(?<=\S)\1(?![\w*])", r"\2", text)  # emphasis, not snake_case
    text = re.sub(r"^\s*[>#-]+\s*", "", text)
    return re.sub(r"\s+", " ", text).strip()


def excerpt(body):
    for block in re.split(r"\n\s*\n", body):
        block = block.strip()
        if not block or block.startswith("#") or block.startswith("```"):
            continue
        flat = strip_markdown(block)
        if not flat:
            continue
        if len(flat) <= EXCERPT_CHARS:
            return flat
        return flat[:EXCERPT_CHARS].rsplit(" ", 1)[0].rstrip(",;:.") + "..."
    return ""


def load_posts():
    posts, topics = [], {}
    if not os.path.isdir(POSTS):
        return posts
    for name in sorted(os.listdir(POSTS)):
        if not name.endswith(".md") or name.startswith("_") or name == "README.md":
            continue
        m = POST_NAME.match(name)
        if not m:
            raise BuildError("posts/%s: expected topic-YYYY-MM-DD.md" % name)
        topic, date = m.group("topic"), m.group("date")
        if topic in topics:
            raise BuildError("posts/%s and posts/%s would both be blog/%s.html; rename one" % (topics[topic], name, topic))
        topics[topic] = name
        with open(os.path.join(POSTS, name), encoding="utf-8") as fh:
            raw = fh.read().lstrip("﻿").strip()
        head = re.match(r"#\s+(.+)\s*\n?", raw)
        if head:
            title, body = head.group(1).strip(), raw[head.end():]
        else:
            title, body = topic.replace("-", " ").replace("_", " ").strip().capitalize(), raw
        y, mo, d = date.split("-")
        posts.append({
            "file": name, "topic": topic, "date": date, "title": title,
            "when": "%s %d, %s" % (MONTHS[int(mo) - 1], int(d), y),
            "excerpt": excerpt(body),
            "minutes": max(1, round(len(body.split()) / 220)),
            "body": render_markdown(body),
        })
    posts.sort(key=lambda p: (p["date"], p["topic"]), reverse=True)
    return posts


def post_nav(posts, i):
    links = []
    if i > 0:
        links.append('<a class="newer" href="%s.html"><span>&larr; NEWER</span>%s</a>' % (posts[i - 1]["topic"], html.escape(posts[i - 1]["title"])))
    if i < len(posts) - 1:
        links.append('<a class="older" href="%s.html"><span>OLDER &rarr;</span>%s</a>' % (posts[i + 1]["topic"], html.escape(posts[i + 1]["title"])))
    return '<nav class="post-nav" aria-label="More posts">%s</nav>' % "".join(links) if links else ""


# ---------- the build ------------------------------------------------------

def context(site, path, page, posts):
    depth = path.count("/")
    root = "../" * depth
    ctx = dict(site, root=root, posts=posts, nav=page.get("nav"),
               home="" if path == "index.html" else root + "index.html")
    page = dict(page, path="" if path == "index.html" else path)
    page.setdefault("og_type", "website")
    for key in ("title", "description"):
        page[key] = fill(page[key], ctx)
    page.setdefault("og_title", page["title"])
    page["og_description"] = fill(page.get("og_description", page["description"]), ctx)
    ctx["page"] = page
    return ctx


def main():
    check = "--check" in sys.argv[1:]
    with open(os.path.join(ROOT, "site.json"), encoding="utf-8") as fh:
        site = json.load(fh)
    pages = site.pop("pages")
    posts = load_posts()
    outputs = {}

    for path, page in pages.items():
        with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
            source = fh.read()
        if "<!-- build:" not in source:
            raise BuildError("%s is listed in site.json but has no build regions" % path)
        outputs[path] = build_regions(source, context(site, path, page, posts), path)

    with open(os.path.join(PARTIALS, "post.html"), encoding="utf-8") as fh:
        template = fh.read()
    for i, post in enumerate(posts):
        path = "blog/%s.html" % post["topic"]
        page = {"title": post["title"] + " · WuBu", "description": post["excerpt"] or post["title"],
                "nav": "blog", "og_type": "article"}
        ctx = context(site, path, page, posts)
        ctx["post"] = dict(post, nav=post_nav(posts, i))
        outputs[path] = build_regions(fill(template, ctx), ctx, path)

    # generated posts whose markdown is gone
    stale = []
    if os.path.isdir(BLOG):
        for name in sorted(os.listdir(BLOG)):
            path = "blog/" + name
            if name.endswith(".html") and path not in outputs:
                with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
                    if GENERATED in fh.read(400):
                        stale.append(path)

    changed = []
    for path, text in outputs.items():
        full = os.path.join(ROOT, path)
        old = open(full, encoding="utf-8").read() if os.path.exists(full) else None
        if old != text:
            changed.append(path)
            if not check:
                os.makedirs(os.path.dirname(full), exist_ok=True)
                with open(full, "w", encoding="utf-8") as fh:
                    fh.write(text)
    if not check:
        for path in stale:
            os.remove(os.path.join(ROOT, path))

    verb = "out of date" if check else "updated"
    for path in changed:
        print("  %s %s" % (verb, path))
    for path in stale:
        print("  %s %s" % ("stale" if check else "removed", path))
    print("%d page%s, %d post%s; %s" % (
        len(pages), "" if len(pages) == 1 else "s", len(posts), "" if len(posts) == 1 else "s",
        "%d file%s %s" % (len(changed) + len(stale), "" if len(changed) + len(stale) == 1 else "s", verb) if changed or stale else "everything up to date"))
    if check and (changed or stale):
        sys.exit(1)


if __name__ == "__main__":
    try:
        main()
    except BuildError as e:
        sys.exit("build-site: %s" % e)
